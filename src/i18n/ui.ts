export const LANGS = ['fr', 'ar', 'en'] as const;
export type Lang = (typeof LANGS)[number];
export const dir = (l: Lang) => (l === 'ar' ? 'rtl' : 'ltr');
export const isLang = (x: string | undefined): x is Lang => LANGS.includes(x as Lang);

/** Prix en dirhams, chiffres occidentaux comme au Maroc. */
export function dh(n: number | string, l: Lang): string {
  const v = Number(n);
  const s = Number.isInteger(v) ? String(v) : v.toFixed(2).replace('.', l === 'en' ? '.' : ',');
  return l === 'ar' ? `${s} درهم` : l === 'en' ? `${s} MAD` : `${s} DH`;
}

